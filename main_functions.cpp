// Подключаем стандартную библиотеку <iostream>:
// она даёт нам потоковый ввод-вывод (cin / cout).
// Без неё компилятор не знает, что такое cin и cout.
#include <iostream>

// using namespace std; позволяет писать cin, cout
// вместо std::cin, std::cout. Удобно, но этим можно
// пользоваться только в маленьких учебных программах.
using namespace std;

// Объявление функции. Схема:
//   тип_результата имя_функции(тип параметр, тип параметр) {
//       ... тело функции ...
//       return результат;   // команда выхода из функции
//   }
//
// Функция add принимает два числа a и b типа long long
// и возвращает их сумму (тоже long long).
long long add(long long a, long long b) {
    return a + b;   // return завершает функцию и выдаёт значение
}

// Функция subtract возвращает разность a - b.
long long subtract(long long a, long long b) {
    return a - b;
}

// Функция multiply возвращает произведение a * b.
long long multiply(long long a, long long b) {
    return a * b;
}

// Функции определены ДО main, потому что main вызывает их —
// компилятор должен увидеть функцию раньше, чем её вызов.
int main() {
    // Эти две строки ускоряют ввод/вывод на олимпиадах:
    // отключаем совместимость с printf/scanf и буферизацию.
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    // Тип long long — 64-битное целое. Берём его, чтобы
    // сумма/произведение не переполнились, если a, b большие.
    long long a, b;

    // cin >> a читает число из ввода, ">>" — потоковый оператор.
    // Вся строка if (cin >> a >> b) — это короткая проверка
    // "удалось ли прочитать оба числа". Если ввода нет — пропустим вывод.
    if (cin >> a >> b) {
        // Вызываем наши функции и печатаем результат в отдельной строке.
        // "\n" — символ перевода строки.
        cout << add(a, b) << "\n";      // печатаем a + b
        cout << subtract(a, b) << "\n"; // печатаем a - b
        cout << multiply(a, b) << "\n"; // печатаем a * b
    }

    // return 0 из main означает "программа завершилась успешно".
    return 0;
}